// Encrypts _private/story.mjs into js/sealed.js.
// Each lock's payload is sealed once per accepted answer with AES-GCM, keyed by PBKDF2(answer, lock salt).
// Usage: node tools/seal.mjs
import { writeFile } from "node:fs/promises";
import { webcrypto as crypto } from "node:crypto";

const { default: locks } = await import("../_private/story.mjs");
const ITER = 150000;
const enc = new TextEncoder();
const b64 = (buf) => Buffer.from(buf).toString("base64");

async function keyFor(secret, salt) {
  const base = await crypto.subtle.importKey("raw", enc.encode(secret), "PBKDF2", false, ["deriveKey"]);
  return crypto.subtle.deriveKey({ name: "PBKDF2", salt, iterations: ITER, hash: "SHA-256" }, base, { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
}

const out = {};
for (const lock of locks) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const data = enc.encode(JSON.stringify(lock.payload));
  const boxes = [];
  for (const answer of lock.answers) {
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, await keyFor(answer, salt), data);
    boxes.push({ iv: b64(iv), ct: b64(ct) });
  }
  // shuffle so box order says nothing about which answer is canonical
  boxes.sort(() => Math.random() - 0.5);
  out[lock.id] = { salt: b64(salt), boxes };
}

await writeFile("js/sealed.js", `// Generated by tools/seal.mjs. Encrypted story data.\nwindow.SEALED = ${JSON.stringify(out)};\nwindow.SEAL_ITER = ${ITER};\n`);
console.log(`Sealed ${locks.length} locks.`);
